// Records the masked-cloud flow from the hosted app as a raw screen capture for the video bot.
import { chromium } from "playwright";
import { renameSync, mkdirSync } from "node:fs";
const base = process.argv[2] ?? "https://plain-letter-hybrid.web.app";
mkdirSync("docs/video/raw", { recursive: true });
const b = await chromium.launch({ headless: false, slowMo: 60 });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: "docs/video/raw", size: { width: 1440, height: 900 } }, locale: "en-US" });
const p = await ctx.newPage();
await p.goto(`${base}/?lang=en`);
await p.waitForTimeout(2500);
await p.selectOption("#sample", "benefit");
await p.waitForTimeout(1200);
await p.click("#read-btn");
await p.waitForSelector("#send-btn");
await p.locator(".pane--answer").scrollIntoViewIfNeeded();
await p.waitForTimeout(2500);
await p.locator(".hidden-items").scrollIntoViewIfNeeded();
await p.waitForTimeout(2500);
await p.fill("#add-value", "Housing Support");
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Hide it" }).click();
await p.waitForTimeout(1500);
await p.getByTestId("masked-preview").scrollIntoViewIfNeeded();
await p.waitForTimeout(2500);
await p.click("#send-btn");
await p.waitForSelector("[data-testid=source-pill], [data-error]", { timeout: 60000 });
await p.locator(".pane--answer").scrollIntoViewIfNeeded();
await p.waitForTimeout(4000);
await p.locator(".ledger").scrollIntoViewIfNeeded();
await p.waitForTimeout(2000);
await p.mouse.wheel(0, 500);
await p.waitForTimeout(3000);
const v = p.video();
await ctx.close();
renameSync(await v.path(), "docs/video/06-08-masked-cloud.webm");
await b.close();
console.log("saved docs/video/06-08-masked-cloud.webm");
